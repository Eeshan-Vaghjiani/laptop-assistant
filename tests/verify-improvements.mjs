import { _electron as electron } from '@playwright/test';
import assert from 'node:assert/strict';
import { mkdtemp } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import path from 'node:path';
import sharp from 'sharp';
const root = process.cwd(), temp = await mkdtemp(path.join(tmpdir(), 'assistant-ui-'));
const env = { ...process.env, ASSISTANT_TEST_PROFILE: path.join(temp, 'profile') }; delete env.ELECTRON_RUN_AS_NODE;
const packaged = process.argv.includes('--packaged');
let app;
try {
  app = await electron.launch({ ...(packaged ? { executablePath: path.join(root, 'dist/Laptop Assistant-win32-x64/Laptop Assistant.exe') } : { args: [root] }), env });
  let page = await app.firstWindow();
  const errors = []; page.on('pageerror', e => errors.push(e.message));
  await page.waitForURL('http://127.0.0.1:*/');
  await page.locator('#connection').filter({ hasText: 'Connected to GitHub Copilot' }).waitFor({ timeout: 60000 });
  assert.equal(await page.locator('#model').inputValue(), 'gpt-6-astra');
  assert.equal(await page.locator('#effort').inputValue(), 'max');
  await page.locator('#effort').selectOption('high');
  await page.waitForFunction(() => !document.getElementById('model').disabled);
  await page.locator('#settings-open').click();
  await page.locator('#access-mode').selectOption('full');
  await page.locator('#settings-save').click();
  await page.locator('#settings-status').filter({ hasText: 'Saved' }).waitFor();
  await page.locator('#settings-close').click();
  const image = path.join(temp, 'no name.png');
  await sharp({ create: { width: 400, height: 300, channels: 3, background: '#ab257b' } }).png().toFile(image);
  await app.evaluate(({ dialog }, image) => { dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [image] }); }, image);
  await page.locator('#add-files').click();
  await page.locator('.attachment-chip span').first().click();
  await page.locator('#preview-body img').waitFor();
  await page.locator('#preview-close').click();
  let release;
  await page.route('**/api/chats/*/message', async route => {
    await new Promise(resolve => { release = resolve; });
    await route.fulfill({ contentType: 'text/event-stream', body: 'event: user\ndata: {"id":"user-1","role":"user","content":"Test"}\n\nevent: status\ndata: {"phase":"thinking","label":"Thinking"}\n\nevent: message\ndata: {"id":"assistant-1","role":"assistant","content":"Test completed."}\n\nevent: done\ndata: {}\n\n' });
  });
  await page.locator('#prompt').fill('UI verification');
  await page.locator('#send').click();
  await page.locator('#stop').waitFor();
  assert.equal(await page.locator('#run-label').innerText(), 'Starting your task');
  await page.screenshot({ path: path.join(temp, 'working.png') });
  while (!release) await new Promise(r => setTimeout(r, 50));
  release();
  await page.locator('#run-label').filter({ hasText: 'Response finished' }).waitFor();
  await page.locator('#stop').waitFor({ state: 'hidden' });
  await page.screenshot({ path: path.join(temp, 'done.png') });
  assert.deepEqual(errors, []);
  await app.close(); app = undefined;
  app = await electron.launch({ ...(packaged ? { executablePath: path.join(root, 'dist/Laptop Assistant-win32-x64/Laptop Assistant.exe') } : { args: [root] }), env });
  page = await app.firstWindow();
  await page.locator('#connection').filter({ hasText: 'Connected to GitHub Copilot' }).waitFor({ timeout: 60000 });
  await page.locator('#new-chat').click();
  assert.equal(await page.locator('#effort').inputValue(), 'high');
  assert.match(await page.locator('#permissions').innerText(), /Full control/);
  console.log('PASS: Astra default, effort persistence, global full control, image preview, working/done states, restart persistence. Screenshots:', temp);
} finally { await app?.close(); }
